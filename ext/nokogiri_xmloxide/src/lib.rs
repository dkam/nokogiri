//! Experimental Nokogiri backend built on xmloxide, a pure-Rust reimplementation
//! of libxml2.
//!
//! This crate builds `nokogiri.bundle` and exports `Init_nokogiri`, the same
//! entry point as the stock C extension in `ext/nokogiri`. Nokogiri's Ruby code
//! in `lib/` loads unchanged on top of it.
//!
//! # Load-time contract
//!
//! `lib/nokogiri` reopens classes the extension defines, so the class hierarchy
//! here must match `ext/nokogiri` exactly or Ruby raises "superclass mismatch".
//! The constants must also be present, because `lib/nokogiri/version/info.rb`
//! reads them to decide which backend is running.
//!
//! # Grading against libxml2
//!
//! The extension reports the libxml2 and libxslt versions from
//! `dependencies.yml`. That makes `Nokogiri.uses_libxml?` (and therefore
//! `Nokogiri.uses_gumbo?`) true, so every test is graded against libxml2's
//! expected behaviour, and `lib/nokogiri.rb` loads HTML5 support. The point of
//! the spike is to measure how closely xmloxide matches libxml2, so this is
//! the honest comparison. `Nokogiri::XMLOXIDE_VERSION` marks the real engine.

mod classes;
mod document;
mod encoding_handler;
mod namespace;
mod node;
mod node_set;
mod syntax_error;
mod test_global_handlers;
mod xpath_context;

use magnus::{Error, Module, RModule, Ruby, Value};

/// libxml2 version Nokogiri vendors (`dependencies.yml`); tests are graded
/// against this version's behaviour.
const IMPERSONATED_LIBXML2_VERSION: &str = "2.14.6";
/// libxslt version Nokogiri vendors (`dependencies.yml`).
const IMPERSONATED_LIBXSLT_VERSION: &str = "1.1.43";
/// Version of the path-dependency checkout in `../../../xmloxide`.
/// xmloxide exports no version constant; keep in sync with its Cargo.toml.
const XMLOXIDE_VERSION: &str = "0.5.0";

#[magnus::init(name = "nokogiri")]
fn init(ruby: &Ruby) -> Result<(), Error> {
    let nokogiri = ruby.define_module("Nokogiri")?;
    let modules = Modules::define(nokogiri)?;

    define_constants(ruby, nokogiri)?;
    define_class_hierarchy(ruby, nokogiri, &modules)?;

    // Stub every native method first (lib/ aliases some at load time), then
    // define real implementations, which replace their stubs.
    ruby.eval::<Value>(STUBS)?;
    encoding_handler::init(ruby, nokogiri)?;
    test_global_handlers::init(nokogiri)?;
    node::init(ruby)?;
    namespace::init(ruby)?;
    node_set::init(ruby)?;
    document::init(ruby)?;
    xpath_context::init(ruby)?;

    Ok(())
}

/// Generated by `scripts/gen-stubs.rb` from `ext/nokogiri/*.c`.
const STUBS: &str = include_str!("stubs.rb");

/// The modules `Init_nokogiri` defines before any classes.
struct Modules {
    html4: RModule,
    html4_sax: RModule,
    html5: RModule,
    xml: RModule,
    xml_sax: RModule,
    xml_xpath: RModule,
    xslt: RModule,
}

impl Modules {
    fn define(nokogiri: RModule) -> Result<Self, Error> {
        nokogiri.define_module("Gumbo")?;
        let html4 = nokogiri.define_module("HTML4")?;
        let html4_sax = html4.define_module("SAX")?;
        let html5 = nokogiri.define_module("HTML5")?;
        let xml = nokogiri.define_module("XML")?;
        let xml_sax = xml.define_module("SAX")?;
        let xml_xpath = xml.define_module("XPath")?;
        let xslt = nokogiri.define_module("XSLT")?;
        // Test-only hooks (test_global_handlers.c).
        nokogiri.define_module("Test")?;

        Ok(Self {
            html4,
            html4_sax,
            html5,
            xml,
            xml_sax,
            xml_xpath,
            xslt,
        })
    }
}

/// Constants `lib/nokogiri/version/info.rb` and the test suite read.
fn define_constants(ruby: &Ruby, nokogiri: RModule) -> Result<(), Error> {
    nokogiri.const_set("XMLOXIDE_VERSION", ruby.str_new(XMLOXIDE_VERSION))?;

    // COMPILED is dotted ("2.14.6"). LOADED uses the libraries' runtime
    // format ("21406"), which version/info.rb unpacks.
    nokogiri.const_set(
        "LIBXML_COMPILED_VERSION",
        ruby.str_new(IMPERSONATED_LIBXML2_VERSION),
    )?;
    nokogiri.const_set(
        "LIBXML_LOADED_VERSION",
        ruby.str_new(&packed_version(IMPERSONATED_LIBXML2_VERSION)),
    )?;
    nokogiri.const_set(
        "LIBXSLT_COMPILED_VERSION",
        ruby.str_new(IMPERSONATED_LIBXSLT_VERSION),
    )?;
    nokogiri.const_set(
        "LIBXSLT_LOADED_VERSION",
        ruby.str_new(&packed_version(IMPERSONATED_LIBXSLT_VERSION)),
    )?;
    nokogiri.const_set("LIBXML_MEMORY_MANAGEMENT", ruby.str_new("xmloxide"))?;

    // Not the packaged C libraries, so libxml2 patch-specific tests skip.
    nokogiri.const_set("PACKAGED_LIBRARIES", false)?;
    nokogiri.const_set("PRECOMPILED_LIBRARIES", false)?;
    nokogiri.const_set("LIBXML2_PATCHES", ruby.qnil())?;
    nokogiri.const_set("LIBXSLT_PATCHES", ruby.qnil())?;

    // xmloxide transcodes with encoding_rs, so grade the encoding tests too.
    nokogiri.const_set("LIBXML_ICONV_ENABLED", true)?;
    nokogiri.const_set("LIBXML_ZLIB_ENABLED", false)?;
    nokogiri.const_set("LIBXML_HTTP_ENABLED", false)?;
    nokogiri.const_set("LIBXSLT_DATETIME_ENABLED", false)?;

    Ok(())
}

/// Packs a dotted version the way libxml2's `xmlParserVersion` and libxslt's
/// `xsltLibxsltVersion` do: "2.14.6" becomes "21406".
fn packed_version(dotted: &str) -> String {
    let mut parts = dotted.split('.').map(|p| p.parse::<u32>().unwrap_or(0));
    let (major, minor, patch) = (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    );
    format!("{major}{minor:02}{patch:02}")
}

#[cfg(test)]
mod tests {
    use super::packed_version;

    #[test]
    fn packs_like_libxml2() {
        assert_eq!(packed_version("2.14.6"), "21406");
        assert_eq!(packed_version("1.1.43"), "10143");
    }
}

/// Mirrors every `rb_define_class_under` call in `ext/nokogiri/*.c`, with the
/// same superclasses. Methods arrive file by file as the backend grows.
fn define_class_hierarchy(ruby: &Ruby, nokogiri: RModule, m: &Modules) -> Result<(), Error> {
    let object = ruby.class_object();

    // Errors (nokogiri.c, xml_syntax_error.c).
    let syntax_error = nokogiri.define_error("SyntaxError", ruby.exception_standard_error())?;
    let xml_syntax_error = m.xml.define_error("SyntaxError", syntax_error)?;
    m.xml_xpath.define_error("SyntaxError", xml_syntax_error)?;

    // Standalone classes.
    nokogiri.define_class("EncodingHandler", object)?;
    m.xml.define_class("ElementContent", object)?;
    m.xml.define_class("Namespace", object)?;
    m.xml.define_class("NodeSet", object)?;
    m.xml.define_class("Reader", object)?;
    m.xml.define_class("XPathContext", object)?;
    m.xslt.define_class("Stylesheet", object)?;
    m.html4.define_class("ElementDescription", object)?;
    m.html4.define_class("EntityLookup", object)?;

    // Validation.
    let schema = m.xml.define_class("Schema", object)?;
    m.xml.define_class("RelaxNG", schema)?;

    // SAX.
    let sax_parser = m.xml_sax.define_class("Parser", object)?;
    m.html4_sax.define_class("Parser", sax_parser)?;
    let sax_parser_context = m.xml_sax.define_class("ParserContext", object)?;
    m.html4_sax
        .define_class("ParserContext", sax_parser_context)?;
    let sax_push_parser = m.xml_sax.define_class("PushParser", object)?;
    m.html4_sax.define_class("PushParser", sax_push_parser)?;

    // The node tree.
    let node = m.xml.define_class("Node", object)?;
    for name in [
        "Attr",
        "AttributeDecl",
        "DTD",
        "ElementDecl",
        "EntityDecl",
        "EntityReference",
        "ProcessingInstruction",
        "Element",
        "DocumentFragment",
    ] {
        m.xml.define_class(name, node)?;
    }
    let character_data = m.xml.define_class("CharacterData", node)?;
    m.xml.define_class("Comment", character_data)?;
    let text = m.xml.define_class("Text", character_data)?;
    m.xml.define_class("CDATA", text)?;

    // Documents.
    let xml_document = m.xml.define_class("Document", node)?;
    let html4_document = m.html4.define_class("Document", xml_document)?;
    m.html5.define_class("Document", html4_document)?;

    Ok(())
}
